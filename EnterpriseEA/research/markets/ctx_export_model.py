"""Export the MKT04 gold context models (plans L and M, long and short) to MQL5 for CtxLimitTester.mq5.

Each model = the walk-forward model the MKT04 test started with (trained on gold M30 decisions before
2025-10-01 minus the 20-bar embargo). Writes:
  CtxLimit/CtxGoldModel.mqh           flattened trees (node arrays) + the feature order
  research/markets/ctx_parity.csv     features and predictions of every test-period decision (EA parity check)

  python ctx_export_model.py
"""
from __future__ import annotations

import math
from pathlib import Path

import lightgbm as lgb
import numpy as np
import pandas as pd

import mkt03_context as m3
import mkt04_context_h4 as m4

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "CtxLimit" / "CtxGoldModel.mqh"
PARITY = HERE / "ctx_parity.csv"
MODELS = [("L", 1, "R_L_p"), ("L", -1, "R_L_n"), ("M", 1, "R_M_p"), ("M", -1, "R_M_n")]
THETA = {"L": None, "M": None}


def flatten(booster):
    """Nodes of every tree: feature, threshold, left, right (child >= 0 node, < 0 leaf ~k), default_left, missing."""
    d = booster.dump_model()
    feat, thr, left, right, dleft, miss, leaves, roots, root_leaf = [], [], [], [], [], [], [], [], []
    for ti in d["tree_info"]:
        t = ti["tree_structure"]
        if "split_index" not in t:                 # single-leaf tree
            roots.append(-1)
            root_leaf.append(len(leaves))
            leaves.append(t["leaf_value"])
            continue
        base = len(feat)

        def node(n):
            k = len(feat)
            feat.append(n["split_feature"]); thr.append(n["threshold"])
            dleft.append(1 if n["default_left"] else 0)
            miss.append({"None": 0, "Zero": 1, "NaN": 2}[n["missing_type"]])
            left.append(0); right.append(0)
            for side, arr in (("left_child", left), ("right_child", right)):
                c = n[side]
                if "split_index" in c:
                    arr[k] = node(c)
                else:
                    arr[k] = -(len(leaves) + 1)
                    leaves.append(c["leaf_value"])
            return k

        roots.append(node(t))
        root_leaf.append(-1)
        assert roots[-1] == base
    return dict(feat=feat, thr=thr, left=left, right=right, dleft=dleft, miss=miss, leaves=leaves, roots=roots,
                root_leaf=root_leaf)


def predict_flat(m, x):
    s = 0.0
    for r, rl in zip(m["roots"], m["root_leaf"]):
        if r < 0:
            s += m["leaves"][rl]
            continue
        k = r
        while True:
            v = x[m["feat"][k]]
            mt = m["miss"][k]
            if mt == 2 and math.isnan(v):
                go_left = m["dleft"][k] == 1
            elif mt == 1 and (math.isnan(v) or abs(v) <= 1e-35):
                go_left = m["dleft"][k] == 1
            else:
                if math.isnan(v):
                    v = 0.0
                go_left = v <= m["thr"][k]
            c = m["left"][k] if go_left else m["right"][k]
            if c < 0:
                s += m["leaves"][-c - 1]
                break
            k = c
    return s


def mql_array(name, typ, vals, fmt):
    body = ",".join(fmt(v) for v in vals)
    return f"const {typ} {name}[{len(vals)}]={{{body}}};\n"


def main():
    g = m4.GROUPS["Vàng"]
    F = m4.build_group("Vàng", g)
    feats = [c for c in F.columns if not c.startswith(("R_", "X_")) and c not in ("time", "sym_name", "i")]
    train = F["time"] < m3.TEST0 - m3.EMBARGO
    test = (F["time"] >= m3.TEST0) & (F["time"] < m3.TEST1)
    src = ["// Generated by research/markets/ctx_export_model.py - do not edit.\n",
           "// MKT04 gold context models (LightGBM, 300 trees, 15 leaves), trained on XAUUSD M30 full-hour decisions\n",
           "// 07/2018 .. 09/2025 (before 2025-10-01 minus 20 bars). Inputs: the CTX_NFEAT features in CTX_FEATURES order.\n",
           f"#define CTX_NFEAT {len(feats)}\n",
           "string CTX_FEATURES[]={" + ",".join(f'"{f}"' for f in feats) + "};\n"]
    par = F.loc[test, ["time"] + feats].copy()
    for plan, d, col in MODELS:
        y = F[col]
        m = train & y.notna()
        mdl = lgb.LGBMRegressor(**m3.PARAMS)
        mdl.fit(F.loc[m, feats], y[m].clip(-1.5, 2.0))
        fl = flatten(mdl.booster_)
        X = F.loc[test, feats].to_numpy()
        ref = mdl.predict(F.loc[test, feats])
        mine = np.array([predict_flat(fl, row) for row in X[:400]])
        err = float(np.max(np.abs(mine - ref[:400])))
        print(plan, d, "trees", len(fl["roots"]), "nodes", len(fl["feat"]), "max |flat - lightgbm|", err, flush=True)
        assert err < 1e-9
        par[f"P_{plan}_{'p' if d == 1 else 'n'}"] = ref
        tag = f"{plan}{'L' if d == 1 else 'S'}"     # LL, LS, ML, MS
        src.append(f"// plan {plan}, {'long' if d == 1 else 'short'}\n")
        src.append(mql_array(f"CTX_{tag}_FEAT", "int", fl["feat"], str))
        src.append(mql_array(f"CTX_{tag}_THR", "double", fl["thr"], lambda v: repr(float(v))))
        src.append(mql_array(f"CTX_{tag}_LEFT", "int", fl["left"], str))
        src.append(mql_array(f"CTX_{tag}_RIGHT", "int", fl["right"], str))
        src.append(mql_array(f"CTX_{tag}_DLEFT", "char", fl["dleft"], str))
        src.append(mql_array(f"CTX_{tag}_MISS", "char", fl["miss"], str))
        src.append(mql_array(f"CTX_{tag}_LEAF", "double", fl["leaves"], lambda v: repr(float(v))))
        src.append(mql_array(f"CTX_{tag}_ROOT", "int", fl["roots"], str))
        src.append(mql_array(f"CTX_{tag}_ROOTLEAF", "int", fl["root_leaf"], str))
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(src), encoding="utf-8")
    par.to_csv(PARITY, index=False, float_format="%.10g")
    print("wrote", OUT, OUT.stat().st_size, "bytes;", PARITY, len(par), "rows")


if __name__ == "__main__":
    main()
