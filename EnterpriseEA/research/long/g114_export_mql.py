"""Freeze the G114 naive-Bayes gate for ProbSetupEA and write it as MQL (ProbSetup/ProbTables.mqh) and JSON
(research/long/out/g114_frozen.json).

  G113_TF=15 python g114_export_mql.py        (gold, families C1 / C2 = G112 impulse / day-extreme chases)

Per family, on every train + validate trade (the 2026 test stays sealed):
  base = logit(p0), weights = Laplace log LR of the factor levels seen >= 30 times (g114_prob.nb_table)
  isotonic blocks = pool-adjacent-violators on the walk-forward out-of-sample naive-Bayes scores and results
                    (g114_prob.walk_family): the calibration the evaluation used, not an in-sample fit
  W / L / var R   = mean win R, mean loss |R| and variance of R of all the trades
  passed          = the G114 pre-registered criteria (false: no family / model passed, see the G114 report)
Factors in EA order: side, sess, d1, h4, adx, vol, div, pos (Tests/prob_setup_oracle.py computes them the same way).
"""
from __future__ import annotations

import json
import math
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

import g108_data as g8
import g114_prob as gp

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MQH = ROOT / "ProbSetup" / "ProbTables.mqh"
JSON = HERE / "out" / "g114_frozen.json"
FACTORS = ["f_side", "f_sess", "f_d1", "f_h4", "f_adx", "f_vol", "f_div", "f_pos"]
FAMS = {"C1": 1, "C2": 2}


def freeze(P: pd.DataFrame) -> dict:
    out = {"symbol": g8.SYMBOL, "tf_min": g8.TF, "factors": [f[2:] for f in FACTORS], "passed": False, "families": []}
    for fam, fid in FAMS.items():
        X = P[(P["fam"] == fam) & (P["period"] != "test")].copy()
        X = X[FACTORS + ["fam", "day", "i", "bars", "d", "R", "win", "time", "exit_t", "kind", "period"]]
        win = X["win"].to_numpy(bool)
        p0, tab = gp.nb_table(X[FACTORS], win)
        W = gp.walk_family(X)
        oos = W[W["nb_raw"].notna()]
        blocks = gp.pav_fit(oos["nb_raw"].to_numpy(), oos["win"].to_numpy(float))
        R = X["R"].to_numpy(float)
        out["families"].append({
            "id": fid, "name": fam, "n": int(len(X)), "p0": p0, "base": math.log(p0 / (1 - p0)),
            "weights": [{"factor": FACTORS.index(f), "name": f[2:], "level": int(v), "w": w} for (f, v), w in sorted(tab.items(), key=lambda kv: (FACTORS.index(kv[0][0]), kv[0][1]))],
            "blocks": [{"lo": float(lo), "p": float(p), "n": float(n)} for lo, p, n in blocks],
            "W": float(R[R > 0].mean()), "L": float(-R[R <= 0].mean()), "var": float(R.var()),
            "oos_n": int(len(oos)), "first": str(pd.Timestamp(int(X["time"].min()), unit="s").date()),
            "last": str(pd.Timestamp(int(X["time"].max()), unit="s").date())})
    return out


def mql(fz: dict) -> str:
    L = ["#ifndef ENTERPRISE_EA_PROB_TABLES_MQH", "#define ENTERPRISE_EA_PROB_TABLES_MQH", "",
         "// GENERATED by research/long/g114_export_mql.py - do not edit by hand.",
         f"// {fz['symbol']} M{fz['tf_min']}, G114 naive-Bayes gate frozen on train + validate trades; test 2026 sealed.",
         f"// passed = {str(fz['passed']).lower()}: no family / model met the G114 pre-registered criteria (shadow use only).",
         f"// factors (EA order): {', '.join(fz['factors'])}", "",
         '#include "ProbDecide.mqh"', "",
         f"#define PS_TF_MIN {fz['tf_min']}", f"#define PS_NFACTORS {len(fz['factors'])}",
         f"#define PS_PASSED {'true' if fz['passed'] else 'false'}", ""]
    fams, lrs, blks = [], [], []
    for f in fz["families"]:
        fams.append(f"   {{ {f['id']}, {f['base']!r}, {f['W']!r}, {f['L']!r}, {f['var']!r}, {'true' if fz['passed'] else 'false'} }}")
        lrs += [f"   {{ {f['id']}, {w['factor']}, {w['level']}, {w['w']!r} }}" for w in f["weights"]]
        blks += [f"   {{ {f['id']}, {b['lo']!r}, {b['p']!r}, {b['n']!r} }}" for b in f["blocks"]]
    names = ", ".join(f'"{f["name"]}"' for f in fz["families"])
    L += [f"string PS_FAM_NAMES[] = {{ {names} }};", "",
          "PsFam PS_FAMS[] =", "  {", ",\n".join(fams), "  };", "",
          "PsLr PS_LR[] =", "  {", ",\n".join(lrs), "  };", "",
          "PsBlock PS_BLOCKS[] =", "  {", ",\n".join(blks), "  };", "", "#endif", ""]
    return "\n".join(L)


def main():
    df = g8.load_m5_raw()
    P = gp.pool(g8.SYMBOL, df)
    fz = freeze(P)
    JSON.parent.mkdir(exist_ok=True)
    JSON.write_text(json.dumps(fz, indent=1), encoding="utf-8")
    MQH.write_text(mql(fz), encoding="utf-8-sig")                # BOM: MetaEditor reads it as Unicode
    for f in fz["families"]:
        print(f["name"], f["n"], "trades, p0 %.3f, %d weights, %d blocks, W %.2f L %.2f" % (f["p0"], len(f["weights"]), len(f["blocks"]), f["W"], f["L"]))
    print("->", MQH, JSON)


if __name__ == "__main__":
    main()
